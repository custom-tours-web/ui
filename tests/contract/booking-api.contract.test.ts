// @vitest-environment jsdom
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import Ajv from 'ajv'
import addFormats from 'ajv-formats'
import { beforeAll, beforeEach, describe, expect, it, vi } from 'vitest'

/**
 * Interface defining the expected structure of the OpenAPI contract.
 * Used to type-check the parsed JSON contract file.
 */
interface BookingApiContract {
  servers: Array<{ url: string }>
  paths: {
    '/api/v1/booking-requests': {
      post: {
        requestBody: {
          required: boolean
          content: {
            'application/json': {
              schema: { $ref: string }
            }
          }
        }
        responses: Record<string, { description: string }>
      }
    }
  }
  components: {
    schemas: {
      BookingRequest: object
    }
  }
}

// Load & parse the OpenAPI specification file synchronously
const contractFile : string = resolve(process.cwd(), 'contracts/booking-api.openapi.json')
const contract = JSON.parse(readFileSync(contractFile, 'utf8')) as BookingApiContract

// Initialize Ajv (Another JSON Schema Validator) for payload validation
const ajv = new Ajv({ allErrors: true, strict: true })
addFormats(ajv) // Add support for standard string formats like 'date'

// Compile the BookingRequest schema from the OpenAPI spec for fast validation during tests
const validateBookingRequest = ajv.compile(contract.components.schemas.BookingRequest)

describe('booking API consumer contract', () => {
  beforeAll(async () => {
    // Compile HAML to HTML to ensure tests run against the production markup structure
    const hamlFile : string = resolve(process.cwd(), 'src/haml/index.haml')
    const renderedPage : string = execFileSync('haml', ['render', hamlFile], {
      encoding: 'utf8',
    })

    // Inject the compiled HTML body into the JSDOM document
    document.body.innerHTML = new DOMParser()
      .parseFromString(renderedPage, 'text/html')
      .body.innerHTML

    // Initialize the booking script after the DOM is ready
    await import('../../src/ts/booking')
  })

  beforeEach(() => {
    // Mock the global fetch API to prevent actual network requests & simulate a successful 201 Created response
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response(null, { status: 201 })))
  })

  it('sends the rendered booking form request according to the OpenAPI contract', async () => {
    // Query all necessary form elements
    const destination = document.querySelector<HTMLSelectElement>('#destination')
    const fullName = document.querySelector<HTMLInputElement>('#full-name')
    const phone = document.querySelector<HTMLInputElement>('#phone-number')
    const fromDate = document.querySelector<HTMLInputElement>('#from-date')
    const toDate = document.querySelector<HTMLInputElement>('#to-date')
    const travelers = document.querySelector<HTMLInputElement>('#travelers')
    const form = document.querySelector<HTMLFormElement>('.booking-form')

    if (!destination || !fullName || !phone || !fromDate || !toDate || !travelers || !form) {
      throw new Error('The rendered booking form is missing required fields.')
    }

    // Populate the form with valid test data
    destination.value = 'ooty'
    fullName.value = 'Mira Rao'
    phone.value = '+91 98765 43210'
    fromDate.value = '2026-11-10'
    toDate.value = '2026-11-12'
    travelers.value = '2'

    // Trigger form submission
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))

    // Wait for the asynchronous fetch call to execute
    await vi.waitFor(() => {
      expect(fetch).toHaveBeenCalledOnce()
    })

    const [requestUrl, requestInit] = vi.mocked(fetch).mock.calls[0] ?? []

    // Assert the request URL matches the server URL defined in the OpenAPI contract
    expect(requestUrl).toBe(
      new URL('/api/v1/booking-requests', contract.servers[0].url).toString(),
    )

    // Assert HTTP method & headers comply with the contract
    expect(requestInit?.method).toBe('POST')
    expect(requestInit?.headers).toEqual({ 'Content-Type': 'application/json' })

    // Assert the contract strictly requires a request body & defines a 201 response
    expect(contract.paths['/api/v1/booking-requests'].post.requestBody.required).toBe(true)
    expect(contract.paths['/api/v1/booking-requests'].post.responses).toHaveProperty('201')

    // Parse the outgoing JSON payload
    const payload: unknown = JSON.parse(String(requestInit?.body))

    // Validate the actual payload generated by the app against the OpenAPI schema
    expect(validateBookingRequest(payload), ajv.errorsText(validateBookingRequest.errors)).toBe(true)
  })

  it('rejects request payloads that violate the contract', () => {
    // Manually verify that the schema validator catches invalid data types
    expect(
      validateBookingRequest({
        fullName: 'Mira Rao',
        phoneNumber: '+91 98765 43210',
        currentLocation: '',
        destination: 'ooty',
        fromDate: '2026-11-10',
        toDate: 'not-a-date', // Invalid format
        numberOfMembers: 0,
        specialRequests: '',
      }),
    ).toBe(false)
  })
})
